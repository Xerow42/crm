def envoyer_email(destinataire, sujet, message_admin_original, message_admin_traduit,
                  nom_utilisateur, date_reclamation, message_client_original, langue_client):
    msg = MIMEMultipart()
    msg['From'] = EMAIL_SENDER
    msg['To'] = destinataire
    msg['Subject'] = sujet

    partie_a_traduire = f"""
Bonjour {nom_utilisateur}, 👋

📅 Nous avons bien reçu votre réclamation soumise le {date_reclamation}. 

📝 Voici le message que vous nous avez envoyé :
« {message_client_original} »

🌐 Et voici notre réponse traduite dans votre langue :
« {message_admin_traduit} »

🙏 Merci pour votre patience et votre compréhension.
N’hésitez pas à nous recontacter si vous avez d’autres questions ou préoccupations.

Cordialement,  
L’équipe FMPS
Translation generated by Googletrans
"""

    bloc_non_traduit = f"""
🛠️ Voici notre réponse originale (en français) :
« {message_admin_original} »
"""

    traducteur = Translator()
    partie_traduite = traducteur.translate(partie_a_traduire, dest=langue_client).text

    corps_email = f"{partie_traduite}\n{bloc_non_traduit}\n\n---------------------------\n\n🇫🇷 Version originale :\n{partie_a_traduire}{bloc_non_traduit}"

    msg.attach(MIMEText(corps_email, 'plain'))

    try:    
        server = smtplib.SMTP(SMTP_SERVER, SMTP_PORT)
        server.starttls()
        server.login(EMAIL_SENDER, EMAIL_PASSWORD)
        server.send_message(msg)
        server.quit()
        print("✅ E-mail envoyé à", destinataire)
    except Exception as e:
        print("❌ Erreur lors de l’envoi de l’e-mail :", e)

