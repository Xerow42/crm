@app.route('/')
def admin_dashboard():
    conn = get_db_connection()
    cursor = conn.cursor()

    cursor.execute("""
        SELECT r.id, u.nom, m.nom_motif, r.description, r.description_originale,
            r.langue_origine, r.sentiment, r.date_reclamation
        FROM reclamations r 
        JOIN utilisateurs u ON r.id_utilisateur = u.id
        JOIN motifs_email m ON r.id_motif = m.id
        ORDER BY r.date_reclamation ASC
    """)
    reclamations = [dict(rec) for rec in cursor.fetchall()]


    # Traduire le motif si besoin
    for rec in reclamations:
        rec['nom_motif'] = GoogleTranslator(source='auto', target='fr').translate(rec['nom_motif'])

    cursor.execute("SELECT * FROM utilisateurs")
    utilisateurs = cursor.fetchall()

    conn.close()
    return render_template('dashboard.html', reclamations=reclamations, utilisateurs=utilisateurs)


